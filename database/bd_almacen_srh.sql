-- Vista de apoyo: stock de cada hospital = conteo inicial + envíos recibidos - consumo (+/- ajustes)
CREATE OR REPLACE VIEW v_stock_sede AS
SELECT s.id_sede, s.nombre AS sede, p.id_producto, p.codigo, p.nombre AS producto,
       COALESCE((SELECT SUM(CASE c.tipo WHEN 'CONSUMO' THEN -c.cantidad ELSE c.cantidad END)
                 FROM consumo_sede c
                 WHERE c.id_sede = s.id_sede AND c.id_producto = p.id_producto AND c.estado = 'ACTIVO'), 0)
     + COALESCE((SELECT SUM(d.cantidad)
                 FROM movimiento m JOIN movimiento_detalle d ON d.id_movimiento = m.id_movimiento
                 WHERE m.tipo = 'SALIDA' AND m.estado = 'ACTIVO' AND m.id_sede = s.id_sede
                   AND d.id_producto = p.id_producto AND m.fecha >= s.fecha_inicio_control), 0) AS stock
FROM sede s CROSS JOIN producto p
WHERE s.tipo = 'HOSPITAL' AND s.fecha_inicio_control IS NOT NULL;
