SET NAMES utf8mb4;
DROP DATABASE IF EXISTS bd_almacen_srh;
CREATE DATABASE bd_almacen_srh CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci;
USE bd_almacen_srh;

-- Personas que usan el sistema. La contraseña se guarda cifrada con BCrypt.
-- El rol SEDE es el encargado de un hospital y queda amarrado a su sede (id_sede).
CREATE TABLE usuario (
    id_usuario  INT AUTO_INCREMENT PRIMARY KEY,
    nombres     VARCHAR(100) NOT NULL,
    username    VARCHAR(50)  NOT NULL UNIQUE,
    password    VARCHAR(100) NOT NULL,
    rol         VARCHAR(20)  NOT NULL,
    activo      TINYINT(1)   NOT NULL DEFAULT 1,
    id_sede     INT NULL,
    CONSTRAINT chk_usuario_rol CHECK (rol IN ('ADMINISTRADOR','JEFE','ASISTENTE','SEDE'))
);

-- Lugares a donde se envían los productos.
CREATE TABLE sede (
    id_sede  INT AUTO_INCREMENT PRIMARY KEY,
    nombre   VARCHAR(80) NOT NULL UNIQUE,
    tipo     VARCHAR(20) NOT NULL,
    activo   TINYINT(1)  NOT NULL DEFAULT 1,
    fecha_inicio_control DATE NULL,   -- desde qué día el hospital controla su stock (empieza en 0)
    CONSTRAINT chk_sede_tipo CHECK (tipo IN ('PLANTA','HOSPITAL'))
);

ALTER TABLE usuario ADD CONSTRAINT fk_usuario_sede FOREIGN KEY (id_sede) REFERENCES sede(id_sede);

CREATE TABLE categoria (
    id_categoria INT AUTO_INCREMENT PRIMARY KEY,
    nombre       VARCHAR(80) NOT NULL UNIQUE
);

CREATE TABLE marca (
    id_marca INT AUTO_INCREMENT PRIMARY KEY,
    nombre   VARCHAR(80) NOT NULL UNIQUE
);

-- El stock solo cambia con los movimientos.
CREATE TABLE producto (
    id_producto     INT AUTO_INCREMENT PRIMARY KEY,
    codigo          VARCHAR(20)  NOT NULL UNIQUE,
    nombre          VARCHAR(120) NOT NULL,
    unidad          VARCHAR(20)  NOT NULL,
    stock           INT NOT NULL DEFAULT 0,
    stock_minimo    INT NOT NULL DEFAULT 0,
    dias_reposicion INT NOT NULL DEFAULT 7,
    minimo_inicial  INT NOT NULL DEFAULT 0,
    id_categoria    INT NOT NULL,
    id_marca        INT NOT NULL,
    activo          TINYINT(1) NOT NULL DEFAULT 1,
    CONSTRAINT fk_producto_categoria FOREIGN KEY (id_categoria) REFERENCES categoria(id_categoria),
    CONSTRAINT fk_producto_marca     FOREIGN KEY (id_marca)     REFERENCES marca(id_marca),
    CONSTRAINT chk_producto_stock CHECK (stock >= 0)
);

-- Cabecera de cada ENTRADA, SALIDA o AJUSTE.
-- Un envío no se borra: se anula (estado). La sede responde si llegó completo (confirmado_sede).
CREATE TABLE movimiento (
    id_movimiento INT AUTO_INCREMENT PRIMARY KEY,
    tipo          VARCHAR(10) NOT NULL,
    fecha         DATETIME    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id_sede       INT NULL,
    id_usuario    INT NOT NULL,
    observacion   VARCHAR(200),
    estado          VARCHAR(10) NOT NULL DEFAULT 'ACTIVO',
    confirmado_sede VARCHAR(10) NULL,
    CONSTRAINT fk_movimiento_sede    FOREIGN KEY (id_sede)    REFERENCES sede(id_sede),
    CONSTRAINT fk_movimiento_usuario FOREIGN KEY (id_usuario) REFERENCES usuario(id_usuario),
    CONSTRAINT chk_movimiento_tipo CHECK (tipo IN ('ENTRADA','SALIDA','AJUSTE')),
    CONSTRAINT chk_movimiento_estado CHECK (estado IN ('ACTIVO','ANULADO')),
    CONSTRAINT chk_movimiento_conf   CHECK (confirmado_sede IN ('CONFORME','DIFERENTE'))
);

-- Productos de cada movimiento.
CREATE TABLE movimiento_detalle (
    id_detalle       INT AUTO_INCREMENT PRIMARY KEY,
    id_movimiento    INT NOT NULL,
    id_producto      INT NOT NULL,
    cantidad_pedida  INT NULL,
    cantidad         INT NOT NULL,
    stock_resultante INT NOT NULL,
    CONSTRAINT fk_detalle_movimiento FOREIGN KEY (id_movimiento) REFERENCES movimiento(id_movimiento),
    CONSTRAINT fk_detalle_producto   FOREIGN KEY (id_producto)   REFERENCES producto(id_producto)
);

-- Lo que pasa dentro de cada sede hospitalaria: consumo por turno y ajustes (cada hospital empieza en 0).
CREATE TABLE consumo_sede (
    id_consumo  INT AUTO_INCREMENT PRIMARY KEY,
    id_sede     INT NOT NULL,
    id_producto INT NOT NULL,
    fecha       DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    tipo        VARCHAR(10) NOT NULL,          -- CONSUMO resta, AJUSTE con signo (INICIAL queda reservado)
    cantidad    INT NOT NULL,
    turno       VARCHAR(10) NULL,              -- solo para CONSUMO
    motivo      VARCHAR(100) NULL,             -- obligatorio para AJUSTE
    id_usuario  INT NOT NULL,
    estado      VARCHAR(10) NOT NULL DEFAULT 'ACTIVO',
    CONSTRAINT fk_consumo_sede     FOREIGN KEY (id_sede)     REFERENCES sede(id_sede),
    CONSTRAINT fk_consumo_producto FOREIGN KEY (id_producto) REFERENCES producto(id_producto),
    CONSTRAINT fk_consumo_usuario  FOREIGN KEY (id_usuario)  REFERENCES usuario(id_usuario),
    CONSTRAINT chk_consumo_tipo   CHECK (tipo IN ('INICIAL','CONSUMO','AJUSTE')),
    CONSTRAINT chk_consumo_turno  CHECK (turno IN ('MANANA','TARDE','NOCHE')),
    CONSTRAINT chk_consumo_estado CHECK (estado IN ('ACTIVO','ANULADO')),
    CONSTRAINT chk_consumo_cant   CHECK (tipo = 'AJUSTE' OR cantidad > 0)
);

-- Historial de errores: cada corrección, anulación o diferencia de envío queda aquí.
CREATE TABLE registro_error (
    id_error           INT AUTO_INCREMENT PRIMARY KEY,
    id_consumo         INT NULL,               -- error en un consumo del hospital
    id_movimiento      INT NULL,               -- error en un envío de logística
    accion             VARCHAR(10) NOT NULL,   -- CORREGIR | ANULAR | DIFERENCIA
    valor_anterior     INT NULL,
    valor_nuevo        INT NULL,
    motivo             VARCHAR(20) NOT NULL,   -- DIGITACION | DUPLICADO | PRODUCTO | ENVIO | OTRO
    detalle            VARCHAR(200) NULL,
    id_usuario_reporta INT NOT NULL,
    fecha_reporte      DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id_usuario_revisa  INT NULL,
    fecha_revision     DATETIME NULL,
    estado             VARCHAR(10) NOT NULL,   -- PENDIENTE | APROBADO | RECHAZADO
    CONSTRAINT fk_error_consumo    FOREIGN KEY (id_consumo)         REFERENCES consumo_sede(id_consumo),
    CONSTRAINT fk_error_movimiento FOREIGN KEY (id_movimiento)      REFERENCES movimiento(id_movimiento),
    CONSTRAINT fk_error_reporta    FOREIGN KEY (id_usuario_reporta) REFERENCES usuario(id_usuario),
    CONSTRAINT fk_error_revisa     FOREIGN KEY (id_usuario_revisa)  REFERENCES usuario(id_usuario),
    CONSTRAINT chk_error_accion CHECK (accion IN ('CORREGIR','ANULAR','DIFERENCIA')),
    CONSTRAINT chk_error_motivo CHECK (motivo IN ('DIGITACION','DUPLICADO','PRODUCTO','ENVIO','OTRO')),
    CONSTRAINT chk_error_estado CHECK (estado IN ('PENDIENTE','APROBADO','RECHAZADO')),
    CONSTRAINT chk_error_origen CHECK (id_consumo IS NOT NULL OR id_movimiento IS NOT NULL)
);

